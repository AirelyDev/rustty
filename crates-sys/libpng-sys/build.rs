//! Build script for libpng-sys (libpng 1.6.43 PNG codec).
//!
//! PORT STATUS: vendored (full library)
//!
//! R3 — self-contained, no ghostty dependency:
//!   1. The upstream C sources for libpng 1.6.43 are vendored in-tree under
//!      `vendor/` (fetched from the exact URL in the reference's
//!      pkg/libpng/build.zig.zon — the deps.files.ghostty.org mirror of the
//!      `glennrp/libpng` 1.6.43 release). This build NEVER references
//!      /Users/gael/projects/ghostty.
//!   2. They are compiled with the `cc` crate, mirroring the reference's
//!      pkg/libpng/build.zig exactly: the same 15 `png*.c` translation units
//!      and the same SIMD-disabling flags (`-DPNG_ARM_NEON_OPT=0`,
//!      `-DPNG_POWERPC_VSX_OPT=0`, `-DPNG_INTEL_SSE_OPT=0`,
//!      `-DPNG_MIPS_MSA_OPT=0`; plus the MSVC ubsan opt-outs). Vendored upstream
//!      warnings are silenced.
//!   3. libpng's build config header is NOT generated by running configure:
//!      ghostty PROVIDES a pre-built `pnglibconf.h` (pkg/libpng/pnglibconf.h),
//!      which is vendored alongside the sources so the vendored
//!      `#include "pnglibconf.h"` (png.h) resolves to it — exactly as the
//!      reference does via `lib.installHeader(b.path("pnglibconf.h"), ...)` +
//!      `lib.addIncludePath(b.path(""))`.
//!   4. System zlib is provided by the `zlib-sys` crate: its `zlib.h` dir
//!      arrives via `DEP_Z_INCLUDE` (pngstruct.h does `#include "zlib.h"`) and
//!      its static `z` archive is linked through the normal dependency (the
//!      reference does the equivalent `lib.linkLibrary(zlib_dep)`).
//!   5. `bindgen` auto-generates the FFI from `wrapper.h` (`#include <png.h>`),
//!      the single public header the reference exposes.
//!   6. `cargo:rustc-link-*` is emitted by `cc` (static archive `libpng`). The
//!      crate declares `links = "png"`, so Cargo enforces a single linkage; the
//!      vendored dir is re-exported via `DEP_PNG_INCLUDE` for downstream crates
//!      (dcimgui-sys).

use std::env;
use std::path::PathBuf;

/// libpng translation units compiled into the static library.
///
/// This is the verbatim `srcs` list from the reference's pkg/libpng/build.zig.
/// The SIMD backends (`arm/`, `intel/`, `mips/`, `powerpc/`, `loongarch/`) are
/// intentionally NOT compiled: the reference disables every SIMD path via the
/// `-DPNG_*_OPT=0` flags below, so those sources are dead and not vendored.
const SOURCES: &[&str] = &[
    "png.c",
    "pngerror.c",
    "pngget.c",
    "pngmem.c",
    "pngpread.c",
    "pngread.c",
    "pngrio.c",
    "pngrtran.c",
    "pngrutil.c",
    "pngset.c",
    "pngtrans.c",
    "pngwio.c",
    "pngwrite.c",
    "pngwtran.c",
    "pngwutil.c",
];

fn main() {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let vendor = manifest_dir.join("vendor");

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_env = env::var("CARGO_CFG_TARGET_ENV").unwrap_or_default();

    let mut build = cc::Build::new();
    build
        // The vendored dir holds png.h, pngconf.h, pngpriv.h, pngstruct.h AND
        // the ghostty-provided pnglibconf.h — one include dir covers the codec
        // sources and its build config (the reference's `addIncludePath("")`).
        .include(&vendor)
        // Vendored upstream code: do not let its warnings fail the host build.
        .warnings(false)
        .flag_if_supported("-w")
        // Reference flags (pkg/libpng/build.zig): disable every SIMD backend so
        // the build is portable and matches the vendored source subset.
        .define("PNG_ARM_NEON_OPT", Some("0"))
        .define("PNG_POWERPC_VSX_OPT", Some("0"))
        .define("PNG_INTEL_SSE_OPT", Some("0"))
        .define("PNG_MIPS_MSA_OPT", Some("0"));

    // The reference adds the MSVC ubsan opt-outs (`target.result.abi == .msvc`).
    if target_env == "msvc" {
        build
            .flag_if_supported("-fno-sanitize=undefined")
            .flag_if_supported("-fno-sanitize-trap=undefined");
    }

    // Portable-build convention shared with the other -sys crates: -fPIC on
    // FreeBSD and musl (needed when this static archive is linked into a PIE).
    if target_os == "freebsd" || target_env == "musl" {
        build.flag_if_supported("-fPIC");
    }

    // System zlib header dir, exported by zlib-sys via `cargo:include`
    // (`DEP_Z_INCLUDE`). Required because `pngstruct.h` does
    // `#include "zlib.h"` (the `z_stream` control block embedded in png_struct).
    let zlib_include = env::var("DEP_Z_INCLUDE").expect("DEP_Z_INCLUDE not set by zlib-sys");
    build.include(&zlib_include);

    for src in SOURCES {
        build.file(vendor.join(src));
        println!("cargo:rerun-if-changed=vendor/{src}");
    }

    // Compiles the vendored sources into a static archive and emits the
    // `cargo:rustc-link-lib=static=png` + search-path directives. Because the
    // crate declares `links = "png"`, Cargo enforces a single linkage.
    build.compile("png");

    // The reference links the system math library on Linux
    // (`lib.linkSystemLibrary("m")`).
    if target_os == "linux" {
        println!("cargo:rustc-link-lib=m");
    }

    // Auto-generate the FFI from the single public header the reference exposes
    // (`wrapper.h`: `png.h`). Uses the vendored libpng include dir (png.h,
    // pnglibconf.h) plus the system-zlib include dir (pngstruct.h pulls
    // <zlib.h>).
    let mut builder = bindgen::Builder::default()
        .header(manifest_dir.join("wrapper.h").to_string_lossy())
        .clang_arg(format!("-I{}", vendor.display()))
        .clang_arg(format!("-I{zlib_include}"));

    // On macOS, libclang (bindgen) does not auto-supply the SDK sysroot the way
    // `cc` does — png.h pulls the standard C headers (stdio.h, setjmp.h, …), so
    // point libclang at the active SDK.
    if target_os == "macos" {
        if let Ok(output) = std::process::Command::new("xcrun")
            .args(["--show-sdk-path"])
            .output()
        {
            if output.status.success() {
                let sdk = String::from_utf8_lossy(&output.stdout).trim().to_string();
                if !sdk.is_empty() {
                    builder = builder.clang_arg(format!("-isysroot{sdk}"));
                }
            }
        }
    }

    let bindings = builder
        // Emit the libpng public surface (png_* functions/types + PNG_* macros).
        .allowlist_function("png_.*")
        .allowlist_type("png_.*")
        .allowlist_var("PNG_.*")
        .parse_callbacks(Box::new(bindgen::CargoCallbacks::new()))
        .generate()
        .expect("unable to generate libpng-sys bindings");
    let out_path = PathBuf::from(env::var("OUT_DIR").unwrap());
    bindings
        .write_to_file(out_path.join("bindings.rs"))
        .expect("unable to write libpng-sys bindings");

    // Re-export the vendored libpng include dir for downstream crates that
    // build against the libpng headers (dcimgui-sys). Cargo sets
    // `DEP_PNG_INCLUDE`.
    println!("cargo:include={}", vendor.display());

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=wrapper.h");
}
