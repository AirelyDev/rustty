//! build.rs — generates `help_strings.Action` (`action_help`) by scanning each
//! CLI action module's `pub fn run` doc block.
//!
//! PORTS: `helpgen.genActions` — the reference iterates `@typeInfo(Action)
//! .@"enum".fields`, opens each `action.file()` (`cli/<name>.zig`), and extracts
//! the `///` doc immediately above `pub fn run`, requiring it to be present
//! (`std.process.exit(1)` otherwise). Here the action set + `Action -> module`
//! mapping come from `rustty.rs`'s `tag_name` (the kebab `+<verb>`; the module
//! file is the tag with `-` → `_`). Keyed by the `Action` variant.

use rustty_helpgen::{doc_above, escape_rust_string};
use std::path::Path;

fn main() {
    let rustty = std::fs::read_to_string("src/rustty.rs").expect("read rustty.rs");
    println!("cargo:rerun-if-changed=src/rustty.rs");

    // (VariantName, kebab-tag) pairs from `tag_name`, in declaration order.
    let actions = parse_tag_names(&rustty);

    let mut out = String::new();
    out.push_str("// @generated by build.rs from the cli action modules — DO NOT EDIT.\n");
    out.push_str(
        "//\n// `help_strings.Action`: the per-action doc text extracted from each action\n",
    );
    out.push_str("// module's `pub fn run` `///` doc block. Every action MUST be documented\n");
    out.push_str("// (the reference `genActions` exits(1) otherwise), so this match is total.\n");
    out.push_str("pub fn action_help(action: crate::rustty::Action) -> &'static str {\n");
    out.push_str("    use crate::rustty::Action;\n");
    out.push_str("    match action {\n");

    for (variant, tag) in &actions {
        let module = format!("src/{}.rs", tag.replace('-', "_"));
        println!("cargo:rerun-if-changed={module}");
        let source = std::fs::read_to_string(&module)
            .unwrap_or_else(|e| panic!("read action module {module}: {e}"));
        let lines: Vec<&str> = source.lines().collect();
        // We're looking for a function named "run".
        let decl = lines
            .iter()
            .position(|l| l.trim_start().starts_with("pub fn run("))
            .unwrap_or_else(|| panic!("no `pub fn run` in {module}"));
        // The function must be preceded by a doc comment.
        let doc = doc_above(&lines, decl).unwrap_or_else(|| {
            panic!("doc comment must be present on run function of the {tag} action!")
        });
        out.push_str(&format!(
            "        Action::{variant} => \"{}\",\n",
            escape_rust_string(&doc)
        ));
    }

    out.push_str("    }\n}\n");

    let dst = Path::new(&std::env::var("OUT_DIR").unwrap()).join("action_help.rs");
    std::fs::write(dst, out).expect("write action_help.rs");
}

/// Parse the `tag_name` match arms (`Action::Version => "version",`) into ordered
/// `(VariantName, kebab-tag)` pairs.
fn parse_tag_names(source: &str) -> Vec<(String, String)> {
    // Restrict to the `fn tag_name` body so unrelated `Action::` uses are ignored.
    let start = source.find("fn tag_name").expect("tag_name present");
    let body = &source[start..];
    let end = body
        .find("\n    }\n")
        .map(|e| e + start)
        .unwrap_or(source.len());
    let body = &source[start..end];

    let mut out = Vec::new();
    for line in body.lines() {
        let t = line.trim();
        // `Action::Version => "version",`
        let Some(rest) = t.strip_prefix("Action::") else {
            continue;
        };
        let Some((variant, after)) = rest.split_once("=>") else {
            continue;
        };
        let variant = variant.trim();
        let after = after.trim();
        if let Some(q1) = after.find('"') {
            if let Some(q2) = after[q1 + 1..].find('"') {
                let tag = &after[q1 + 1..q1 + 1 + q2];
                out.push((variant.to_string(), tag.to_string()));
            }
        }
    }
    out
}
