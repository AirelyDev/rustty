// PORT NOTE: the reference declares `octants_len`/`octants` as `comptime` locals
// inside `draw1CD00_1CDE5`. The parse is reproduced by a module-level `const fn`
// (`build_octants`) whose const evaluation is Rust's equivalent of `comptime`,
// yielding the same static lookup table embedded in the binary. `OCTANTS_LEN` is
// hoisted to module scope so `build_octants`'s return type can name it (the
// reference's local `octants_len` still appears inside the fn and equals this).
const OCTANTS_LEN: usize = (octant_max - octant_min + 1) as usize;

// Octant representation. We use the funny numeric string keys
// so its easier to parse the actual name used in the Symbols for
// Legacy Computing spec.
// const Octant = packed struct(u8) {
//     @"1": bool = false,
//     ...
//     @"8": bool = false,
// };
//
// PORT NOTE: the reference `packed struct(u8)` with numeric field names
// `@"1"`..`@"8"` maps to a `[bool; 8]` array indexed 0-based (`@"1"` -> `[0]`,
// ..., `@"8"` -> `[7]`).
//
// Parse the octant data. This is all done at comptime so
// that this is static data that is embedded in the binary.
const fn build_octants() -> [[bool; 8]; OCTANTS_LEN] {
    // @setEvalBranchQuota(10_000);
    //
    // PORT NOTE: `@setEvalBranchQuota` is a Zig comptime-budget hint with no Rust
    // analogue (const eval has no such cap); it is preserved as a reference note.

    // var result: [octants_len]Octant = @splat(.{});
    let mut result = [[false; 8]; OCTANTS_LEN];
    // var i: usize = 0;
    let mut i: usize = 0;

    // const data = @embedFile("octants.txt");
    let data = include_bytes!("octants.txt");
    // var it = std.mem.splitScalar(u8, data, '\n');
    // while (it.next()) |raw_line| {
    //
    // PORT NOTE: `splitScalar(u8, data, '\n')` is reproduced by scanning byte
    // ranges `[start..pos]` delimited by `'\n'` (including the trailing segment
    // after the final newline, matching `splitScalar`).
    let n = data.len();
    let mut start = 0usize;
    let mut pos = 0usize;
    loop {
        if pos == n || data[pos] == b'\n' {
            // raw_line = data[start..pos]
            // Trim \r so this works with both LF and CRLF line endings,
            // since git may convert octants.txt to CRLF on Windows checkouts.
            // const line = if (raw_line.len > 0 and raw_line[raw_line.len - 1] == '\r')
            //     raw_line[0 .. raw_line.len - 1]
            // else
            //     raw_line;
            let mut end = pos;
            if end > start && data[end - 1] == b'\r' {
                end -= 1;
            }
            let len = end - start;

            // Skip comments
            // if (line.len == 0 or line[0] == '#') continue;
            if !(len == 0 || data[start] == b'#') {
                // const current = &result[i];
                // i += 1;
                //
                // PORT NOTE: `current` is written directly as `result[i]` (Rust
                // has no aliasing local for a const-eval array slot); `i` is
                // advanced after the field writes, matching the reference order.

                // Octants are in the format "BLOCK OCTANT-1235". The numbers
                // at the end are keys into our packed struct. Since we're
                // at comptime we can metaprogram it all.
                // const idx = std.mem.indexOfScalar(u8, line, '-').?;
                let mut idx = start;
                while idx < end && data[idx] != b'-' {
                    idx += 1;
                }
                // for (line[idx + 1 ..]) |c| @field(current, &.{c}) = true;
                let mut c = idx + 1;
                while c < end {
                    result[i][(data[c] - b'1') as usize] = true;
                    c += 1;
                }
                i += 1;
            }

            if pos == n {
                break;
            }
            start = pos + 1;
        }
        pos += 1;
    }

    // assert(i == octants_len);
    assert!(i == OCTANTS_LEN);
    // break :octants result;
    result
}

