// fn circlePiece(
//     canvas: *font.sprite.Canvas,
//     width: u32,
//     height: u32,
//     metrics: font.Metrics,
//     x: f64,
//     y: f64,
//     w: f64,
//     h: f64,
//     corner: Corner,
// ) !void {
#[allow(clippy::too_many_arguments)]
fn circlePiece(
    canvas: &mut Canvas,
    width: u32,
    height: u32,
    metrics: Metrics,
    x: f64,
    y: f64,
    w: f64,
    h: f64,
    corner: Corner,
) -> Result<(), StrokeError> {
    // Radius in pixels of the arc we need to draw.
    // const wdth: f64 = @as(f64, @floatFromInt(width)) * w;
    let wdth: f64 = width as f64 * w;
    // const hght: f64 = @as(f64, @floatFromInt(height)) * h;
    let hght: f64 = height as f64 * h;

    // Position in pixels (rather than cells) for x/y
    // const xp: f64 = @as(f64, @floatFromInt(width)) * x;
    let xp: f64 = width as f64 * x;
    // const yp: f64 = @as(f64, @floatFromInt(height)) * y;
    let yp: f64 = height as f64 * y;

    // Set the clip so we don't include anything outside of the cell.
    // canvas.clip_left = canvas.padding_x;
    canvas.clip_left = canvas.padding_x;
    // canvas.clip_right = canvas.padding_x;
    canvas.clip_right = canvas.padding_x;
    // canvas.clip_top = canvas.padding_y;
    canvas.clip_top = canvas.padding_y;
    // canvas.clip_bottom = canvas.padding_y;
    canvas.clip_bottom = canvas.padding_y;

    // Coefficient for approximating a circular arc.
    // const c: f64 = (std.math.sqrt2 - 1.0) * 4.0 / 3.0;
    let c: f64 = (SQRT_2 - 1.0) * 4.0 / 3.0;
    // const cw = c * wdth;
    let cw = c * wdth;
    // const ch = c * hght;
    let ch = c * hght;

    // const thick: f64 = @floatFromInt(metrics.box_thickness);
    let thick: f64 = metrics.box_thickness as f64;
    // const ht = thick * 0.5;
    let ht = thick * 0.5;

    // var path = canvas.staticPath(2);
    let mut path = canvas.staticPath::<2>();

    // switch (corner) {
    match corner {
        // .tl => {
        Corner::Tl => {
            // path.moveTo(wdth - xp, ht - yp);
            path.move_to(wdth - xp, ht - yp);
            // path.curveTo(
            //     wdth - cw - xp,
            //     ht - yp,
            //     ht - xp,
            //     hght - ch - yp,
            //     ht - xp,
            //     hght - yp,
            // );
            path.curve_to(
                wdth - cw - xp,
                ht - yp,
                ht - xp,
                hght - ch - yp,
                ht - xp,
                hght - yp,
            );
        }
        // .tr => {
        Corner::Tr => {
            // path.moveTo(wdth - xp, ht - yp);
            path.move_to(wdth - xp, ht - yp);
            // path.curveTo(
            //     wdth + cw - xp,
            //     ht - yp,
            //     wdth * 2 - ht - xp,
            //     hght - ch - yp,
            //     wdth * 2 - ht - xp,
            //     hght - yp,
            // );
            path.curve_to(
                wdth + cw - xp,
                ht - yp,
                wdth * 2.0 - ht - xp,
                hght - ch - yp,
                wdth * 2.0 - ht - xp,
                hght - yp,
            );
        }
        // .bl => {
        Corner::Bl => {
            // path.moveTo(ht - xp, hght - yp);
            path.move_to(ht - xp, hght - yp);
            // path.curveTo(
            //     ht - xp,
            //     hght + ch - yp,
            //     wdth - cw - xp,
            //     hght * 2 - ht - yp,
            //     wdth - xp,
            //     hght * 2 - ht - yp,
            // );
            path.curve_to(
                ht - xp,
                hght + ch - yp,
                wdth - cw - xp,
                hght * 2.0 - ht - yp,
                wdth - xp,
                hght * 2.0 - ht - yp,
            );
        }
        // .br => {
        Corner::Br => {
            // path.moveTo(wdth * 2 - ht - xp, hght - yp);
            path.move_to(wdth * 2.0 - ht - xp, hght - yp);
            // path.curveTo(
            //     wdth * 2 - ht - xp,
            //     hght + ch - yp,
            //     wdth + cw - xp,
            //     hght * 2 - ht - yp,
            //     wdth - xp,
            //     hght * 2 - ht - yp,
            // );
            path.curve_to(
                wdth * 2.0 - ht - xp,
                hght + ch - yp,
                wdth + cw - xp,
                hght * 2.0 - ht - yp,
                wdth - xp,
                hght * 2.0 - ht - yp,
            );
        }
    }

    // try canvas.strokePath(path.wrapped_path, .{
    //     .line_cap_mode = .butt,
    //     .line_width = @floatFromInt(metrics.box_thickness),
    // }, .on);
    canvas.strokePath(
        &path.wrapped_path,
        StrokeOptions {
            line_cap_mode: CapMode::Butt,
            line_width: metrics.box_thickness as f64,
            ..Default::default()
        },
        Color::ON,
    )
}
