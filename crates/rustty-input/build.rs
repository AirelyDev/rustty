//! build.rs — generates `help_strings.KeybindAction` (`keybind_help`) by scanning
//! the ported `binding.rs` `Action` enum for each variant's `///` doc block.
//!
//! PORTS: `helpgen.genKeybindActions` — the reference iterates
//! `@typeInfo(KeybindAction).@"union".fields` (skipping `_`-prefixed) and runs
//! the same `genConfigField` doc-scan over `input/Binding.zig`. Here the union
//! field set is `Action::FIELD_NAMES` (the single-source-of-truth order); each
//! snake field name maps to its PascalCase Rust variant, whose `///` block is
//! extracted. Keyed by the union field name (== the reference `field.name`).

use rustty_helpgen::{doc_above, escape_rust_string};
use std::path::Path;

fn main() {
    let src = "src/binding.rs";
    println!("cargo:rerun-if-changed={src}");
    let source = std::fs::read_to_string(src).expect("read binding.rs");
    let lines: Vec<&str> = source.lines().collect();

    let field_names = parse_field_names(&source);
    let (enum_start, enum_end) = find_action_enum(&lines);

    let mut out = String::new();
    out.push_str("// @generated by build.rs from binding.rs — DO NOT EDIT.\n");
    out.push_str(
        "//\n// `help_strings.KeybindAction`: the per-action doc text extracted from each\n",
    );
    out.push_str("// `Action` variant's `///` doc block. `None` (via the `_` arm) == the\n");
    out.push_str("// reference's `@hasDecl(help_strings.KeybindAction, field) == false`.\n");
    out.push_str("pub fn keybind_help(name: &[u8]) -> Option<&'static [u8]> {\n");
    out.push_str("    match name {\n");
    for name in &field_names {
        // if (field.name[0] == '_') continue;
        if name.starts_with('_') {
            continue;
        }
        let pascal = snake_to_pascal(name);
        let doc =
            find_variant(&lines, enum_start, enum_end, &pascal).and_then(|i| doc_above(&lines, i));
        if let Some(bytes) = doc {
            out.push_str(&format!(
                "        b\"{name}\" => Some(\"{}\".as_bytes()),\n",
                escape_rust_string(&bytes)
            ));
        }
        // An undocumented variant gets no arm (falls through to `_ => None`).
    }
    out.push_str("        _ => None,\n    }\n}\n");

    let dst = Path::new(&std::env::var("OUT_DIR").unwrap()).join("keybind_help.rs");
    std::fs::write(dst, out).expect("write keybind_help.rs");
}

/// Parse `Action::FIELD_NAMES` into the ordered union field names.
fn parse_field_names(source: &str) -> Vec<String> {
    let start = source.find("FIELD_NAMES").expect("FIELD_NAMES present");
    let block_start = source[start..].find("&[").expect("FIELD_NAMES opening") + start;
    let block_end = source[block_start..]
        .find("];")
        .expect("FIELD_NAMES closing")
        + block_start;
    let block = &source[block_start..block_end];
    let b = block.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'"' {
            let s = i + 1;
            let mut j = s;
            while j < b.len() && b[j] != b'"' {
                j += 1;
            }
            out.push(String::from_utf8_lossy(&b[s..j]).into_owned());
            i = j + 1;
        } else {
            i += 1;
        }
    }
    out
}

/// The `[start, end)` line range of the `pub enum Action {` body (brace-matched).
fn find_action_enum(lines: &[&str]) -> (usize, usize) {
    let start = lines
        .iter()
        .position(|l| l.trim_start().starts_with("pub enum Action {"))
        .expect("pub enum Action");
    let mut depth = 0usize;
    for (off, line) in lines[start..].iter().enumerate() {
        depth += line.matches('{').count();
        depth -= line.matches('}').count();
        if depth == 0 {
            return (start, start + off + 1);
        }
    }
    panic!("unterminated Action enum");
}

/// The line of the `<pascal>` variant declaration within `[start, end)`.
fn find_variant(lines: &[&str], start: usize, end: usize, pascal: &str) -> Option<usize> {
    let with_paren = format!("{pascal}(");
    let with_comma = format!("{pascal},");
    (start..end).find(|&i| {
        let t = lines[i].trim_start();
        t.starts_with(&with_paren) || t == with_comma
    })
}

/// snake_case union field name → PascalCase Rust variant (`copy_to_clipboard`
/// → `CopyToClipboard`). The port's variants use plain segment-capitalization.
fn snake_to_pascal(name: &str) -> String {
    name.split('_')
        .map(|seg| {
            let mut c = seg.chars();
            match c.next() {
                Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
                None => String::new(),
            }
        })
        .collect()
}
