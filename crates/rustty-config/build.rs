//! build.rs — generates `help_strings.Config` (`config_help`) by scanning the
//! ported `config_struct.rs` for each `Config` field's `///` doc block.
//!
//! PORTS: `helpgen.genConfig` / `genConfigField` — the per-field extraction the
//! reference runs at build time (src/build/HelpStrings.zig → src/helpgen.zig).
//! This is the faithful analog: parse the source, emit the table into OUT_DIR.
//! The field set + `cli-name -> Key` mapping come from the landed `CONFIG_FIELDS`
//! table (the reference iterates `@typeInfo(Config).@"struct".fields`, skipping
//! `_`-prefixed internals — `CONFIG_FIELDS` is exactly that non-`_` set).

use rustty_helpgen::{doc_above, escape_rust_string};
use std::path::Path;

fn main() {
    let src_path = "src/config_struct.rs";
    println!("cargo:rerun-if-changed={src_path}");
    let source = std::fs::read_to_string(src_path).expect("read config_struct.rs");
    let lines: Vec<&str> = source.lines().collect();

    // The ordered (cli-name, Key::Variant) pairs — the reference's field iteration.
    let fields = parse_config_fields(&source);

    let mut out = String::new();
    out.push_str("// @generated by build.rs from config_struct.rs — DO NOT EDIT.\n");
    out.push_str(
        "//\n// `help_strings.Config`: the per-key doc text extracted from each `Config`\n",
    );
    out.push_str("// field's `///` doc block. `None` == the reference's\n");
    out.push_str("// `@hasDecl(help_strings.Config, field) == false` (an undocumented field).\n");
    out.push_str("pub fn config_help(key: crate::config_struct::Key) -> Option<&'static [u8]> {\n");
    out.push_str("    use crate::config_struct::Key;\n");
    out.push_str("    match key {\n");
    for (cli, variant) in &fields {
        let rust_field = cli.replace('-', "_");
        let doc = find_field_decl(&lines, &rust_field).and_then(|i| doc_above(&lines, i));
        match doc {
            Some(bytes) => out.push_str(&format!(
                "        Key::{variant} => Some(\"{}\".as_bytes()),\n",
                escape_rust_string(&bytes)
            )),
            None => out.push_str(&format!("        Key::{variant} => None,\n")),
        }
    }
    out.push_str("    }\n}\n");

    let dst = Path::new(&std::env::var("OUT_DIR").unwrap()).join("config_help.rs");
    std::fs::write(dst, out).expect("write config_help.rs");
}

/// The struct-field declaration line for `rust_field` (`pub <rust_field>:`).
fn find_field_decl(lines: &[&str], rust_field: &str) -> Option<usize> {
    let needle = format!("pub {rust_field}:");
    lines
        .iter()
        .position(|l| l.trim_start().starts_with(&needle))
}

/// Parse the `CONFIG_FIELDS` table into ordered `(cli_name, Key::Variant)` pairs.
fn parse_config_fields(source: &str) -> Vec<(String, String)> {
    let start = source
        .find("const CONFIG_FIELDS")
        .expect("CONFIG_FIELDS definition present");
    let block_start = source[start..].find("&[").expect("CONFIG_FIELDS opening") + start;
    let block_end = source[block_start..]
        .find("];")
        .expect("CONFIG_FIELDS closing")
        + block_start;
    let block = &source[block_start..block_end];

    let names = collect_byte_strings(block);
    let variants = collect_key_variants(block);
    assert_eq!(
        names.len(),
        variants.len(),
        "CONFIG_FIELDS name/variant count mismatch ({} names, {} variants)",
        names.len(),
        variants.len()
    );
    names.into_iter().zip(variants).collect()
}

/// Every `b"..."` byte-string literal in `block`, in order.
fn collect_byte_strings(block: &str) -> Vec<String> {
    let b = block.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i + 1 < b.len() {
        if b[i] == b'b' && b[i + 1] == b'"' {
            let mut j = i + 2;
            let s = j;
            while j < b.len() && b[j] != b'"' {
                j += 1;
            }
            out.push(String::from_utf8_lossy(&b[s..j]).into_owned());
            i = j + 1;
        } else {
            i += 1;
        }
    }
    out
}

/// Every `Key::<Ident>` variant in `block`, in order.
fn collect_key_variants(block: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = block;
    while let Some(pos) = rest.find("Key::") {
        let after = &rest[pos + 5..];
        let end = after
            .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .unwrap_or(after.len());
        out.push(after[..end].to_string());
        rest = &after[end..];
    }
    out
}
