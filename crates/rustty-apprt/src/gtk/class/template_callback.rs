//! rustty-apprt::gtk::class::template_callback
//!
//! PORTS: ghostty `src/apprt/gtk/class.zig:330-352` `Class.bindTemplateCallback`
//! — binds a C function to a template callback name with
//! `gtk_widget_class_bind_template_callback_full`, so GTK's own C builder scope
//! (`GtkBuilderCScope`) creates the signal and expression closures, exactly as
//! the reference does.
//!
//! NEW-FINDINGS N516: the port used gtk4-rs's `#[template_callbacks]` /
//! `bind_template_instance_callbacks`, which installs gtk4-rs's
//! `BuilderRustScope`. That scope hands GTK an already-sunk `GClosure`, and
//! `gtk_builder_connect_signals` adds a reference when it connects it and never
//! drops it, so every template instantiation leaked every callback closure (and
//! what it captured). GTK's C scope returns floating closures
//! (`g_cclosure_new_object` / `g_cclosure_new_object_swap`), which the
//! connection sinks: nothing leaks, as in Ghostty.
//!
//! Each callback is an `unsafe extern "C"` trampoline generated by
//! [`bind_template_callbacks!`] from the C signature the signal (or expression
//! closure) is marshalled with: the emitter, the signal arguments, then the
//! template instance (the closure's data; a `swapped` connection puts it first).
//! A handler may declare fewer trailing parameters than GTK passes (the C
//! calling conventions GTK runs on let the caller own the argument area; GTK
//! and Ghostty rely on it). The trampoline converts the C arguments to the
//! Rust types the ported handler takes and calls it; a panic in a handler
//! aborts the process (it cannot unwind out of an `extern "C"` function), as it
//! did under glib-rs's closure marshaller.

use core::ffi::CStr;

use gtk4::subclass::prelude::*;

/// Binds `func`, a C function, as the template callback `name` of the widget
/// class `klass`. PORTS: `class.zig:330-352` `Class.bindTemplateCallback`.
///
/// # Safety
///
/// `func` must be an `unsafe extern "C" fn` whose parameters and return type
/// match what GTK passes for every signal or expression closure the class's
/// template binds to `name` (trailing parameters may be omitted). The class's
/// template must already be set (`bind_template`).
pub(crate) unsafe fn bind_template_callback<C>(klass: &mut C, name: &CStr, func: *const ())
where
    C: ClassStruct,
    C::Type: WidgetImpl,
{
    // SAFETY: a widget subclass's class struct starts with its parent's class
    // struct and so with `GtkWidgetClass` (the cast gtk4-rs's
    // `WidgetClassExt::set_template_scope` makes); `func` is a C function per
    // this function's contract, and `GCallback` is the type-erased C function
    // pointer GTK casts back to the signal's signature.
    unsafe {
        let callback: unsafe extern "C" fn() = core::mem::transmute(func);
        gtk4::ffi::gtk_widget_class_bind_template_callback_full(
            (klass as *mut C).cast::<gtk4::ffi::GtkWidgetClass>(),
            name.as_ptr(),
            Some(callback),
        );
    }
}

/// Binds template callbacks through GTK's C builder scope.
///
/// ```ignore
/// bind_template_callbacks!(klass;
///     c"focus_enter" => Surface::focus_enter, (ec: obj(gtk4::EventControllerFocus), this: obj(Surface));
///     c"key_pressed" => Surface::key_pressed, (ec: obj(gtk4::EventControllerKey), keyval: prim(u32),
///         keycode: prim(u32), mods: glib(gdk4::ModifierType), this: obj(Surface)) -> glib(bool);
/// );
/// ```
///
/// Each parameter is `name: kind(type)`, in the C order; the handler is called
/// with the converted arguments in the same order. Parameter kinds:
///
/// | kind              | C type                         | handler gets |
/// |-------------------|--------------------------------|--------------|
/// | `obj(T)`          | `T`'s instance pointer         | `&T` (borrowed, no reference taken) |
/// | `opt_obj(T)`      | nullable instance pointer      | `Option<T>` (a new reference) |
/// | `opt_obj_ref(T)`  | nullable instance pointer      | `Option<&T>` |
/// | `value()`         | `const GValue *`               | `&glib::Value` |
/// | `str()`           | `const char *`, UTF-8          | `&str` (invalid UTF-8 replaced) |
/// | `opt_str()`       | nullable `const char *`        | `Option<&str>` |
/// | `opt_string()`    | nullable `const char *`        | `Option<String>` |
/// | `opt_boxed(T)`    | nullable `T *` (Rust boxed)    | `Option<T>` (a clone, the boxed copy) |
/// | `prim(T)`         | `T` (`u32`, `i32`, `u64`, `f64`) | `T` |
/// | `boolean()`       | `gboolean`                     | `bool` |
/// | `glib(T)`         | `T`'s `IntoGlib` C type (enums, flags) | `T` |
///
/// Return kinds: none (`void`); `glib(T)` (`bool` and `glib::Propagation` as
/// `gboolean`, enums and flags as their C type); `full(T)` (an object, a
/// reference transferred to GTK); `none(T)` (an object GTK does not take a
/// reference to: the handler's value must be kept alive elsewhere);
/// `string()` (a nullable `g_malloc`ed string GTK takes, as the reference's
/// `glib.ext.dupeZ`).
macro_rules! bind_template_callbacks {
    ($klass:expr; $(
        $name:literal => $f:path,
            ( $( $arg:ident : $kind:ident ( $($ty:tt)* ) ),* $(,)? )
            $( -> $rkind:ident ( $($rty:tt)* ) )? ;
    )*) => {{
        let klass = $klass;
        $({
            unsafe extern "C" fn trampoline(
                $( $arg: $crate::gtk::class::template_callback::tcb_c_ty!($kind($($ty)*)) ),*
            ) $( -> $crate::gtk::class::template_callback::tcb_c_ret_ty!($rkind($($rty)*)) )? {
                // SAFETY: GTK calls this with the arguments of the signal or
                // expression closure the template binds to this name, whose C
                // types are the ones declared here (the binding's contract);
                // each pointer is valid for the call. (The `prim` and
                // `boolean` conversions need no `unsafe`.)
                $( #[allow(unused_unsafe)] let $arg = unsafe {
                    $crate::gtk::class::template_callback::tcb_from_c!($kind($($ty)*) $arg)
                }; )*
                let ret = $f( $( $crate::gtk::class::template_callback::tcb_pass!($kind $arg) ),* );
                $crate::gtk::class::template_callback::tcb_ret!([ $( $rkind($($rty)*) )? ] ret)
            }
            // SAFETY: `trampoline` takes the C signature GTK calls this name
            // with (see above), and `bind_template` ran first.
            unsafe {
                $crate::gtk::class::template_callback::bind_template_callback(
                    &mut *klass,
                    $name,
                    trampoline as *const (),
                );
            }
        })*
    }};
}

macro_rules! tcb_c_ty {
    (obj($($t:tt)*)) => { <$($t)* as ::glib::translate::GlibPtrDefault>::GlibType };
    (opt_obj($($t:tt)*)) => { <$($t)* as ::glib::translate::GlibPtrDefault>::GlibType };
    (opt_obj_ref($($t:tt)*)) => { <$($t)* as ::glib::translate::GlibPtrDefault>::GlibType };
    (value()) => { *const ::glib::gobject_ffi::GValue };
    (str()) => { *const ::core::ffi::c_char };
    (opt_str()) => { *const ::core::ffi::c_char };
    (opt_string()) => { *const ::core::ffi::c_char };
    (opt_boxed($($t:tt)*)) => { *const $($t)* };
    (prim($($t:tt)*)) => { $($t)* };
    (boolean()) => { ::glib::ffi::gboolean };
    (glib($($t:tt)*)) => { <$($t)* as ::glib::translate::IntoGlib>::GlibType };
}

macro_rules! tcb_from_c {
    (obj($($t:tt)*) $a:ident) => {
        ::glib::translate::from_glib_borrow::<_, $($t)*>($a)
    };
    (opt_obj($($t:tt)*) $a:ident) => {
        ::glib::translate::from_glib_none::<_, Option<$($t)*>>($a)
    };
    (opt_obj_ref($($t:tt)*) $a:ident) => {
        if $a.is_null() {
            None
        } else {
            Some(::glib::translate::from_glib_borrow::<_, $($t)*>($a))
        }
    };
    (value() $a:ident) => {
        ::glib::Value::from_glib_ptr_borrow($a)
    };
    (str() $a:ident) => {
        ::core::ffi::CStr::from_ptr($a).to_string_lossy()
    };
    (opt_str() $a:ident) => {
        if $a.is_null() {
            None
        } else {
            Some(::core::ffi::CStr::from_ptr($a).to_string_lossy())
        }
    };
    (opt_string() $a:ident) => {
        ::glib::translate::from_glib_none::<_, Option<String>>($a)
    };
    (opt_boxed($($t:tt)*) $a:ident) => {
        if $a.is_null() {
            None
        } else {
            Some(<$($t)* as ::core::clone::Clone>::clone(&*$a))
        }
    };
    (prim($($t:tt)*) $a:ident) => {
        $a
    };
    (boolean() $a:ident) => {
        $a != ::glib::ffi::GFALSE
    };
    (glib($($t:tt)*) $a:ident) => {
        ::glib::translate::from_glib::<_, $($t)*>($a)
    };
}

macro_rules! tcb_pass {
    (obj $a:ident) => {
        &*$a
    };
    (opt_obj_ref $a:ident) => {
        $a.as_deref()
    };
    (str $a:ident) => {
        &*$a
    };
    (opt_str $a:ident) => {
        $a.as_deref()
    };
    ($k:ident $a:ident) => {
        $a
    };
}

macro_rules! tcb_c_ret_ty {
    (glib($($t:tt)*)) => { <$($t)* as ::glib::translate::IntoGlib>::GlibType };
    (full($($t:tt)*)) => { <$($t)* as ::glib::translate::GlibPtrDefault>::GlibType };
    (none($($t:tt)*)) => { <$($t)* as ::glib::translate::GlibPtrDefault>::GlibType };
    (string()) => { *mut ::core::ffi::c_char };
}

macro_rules! tcb_ret {
    ([] $r:ident) => {{
        let () = $r;
    }};
    ([glib($($t:tt)*)] $r:ident) => {
        ::glib::translate::IntoGlib::into_glib($r)
    };
    ([full($($t:tt)*)] $r:ident) => {
        ::glib::translate::IntoGlibPtr::into_glib_ptr($r)
    };
    ([none($($t:tt)*)] $r:ident) => {
        ::glib::prelude::ObjectType::as_ptr(&$r)
    };
    ([string()] $r:ident) => {
        ::glib::translate::ToGlibPtr::<*mut ::core::ffi::c_char>::to_glib_full(&$r)
    };
}

pub(crate) use {bind_template_callbacks, tcb_c_ret_ty, tcb_c_ty, tcb_from_c, tcb_pass, tcb_ret};
