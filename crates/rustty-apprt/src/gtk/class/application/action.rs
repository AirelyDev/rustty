/// Reload the configuration for the application and propagate it
/// across the entire application and all terminals.
///
/// `pub fn reloadConfig(self, target, opts) !void` (`:2443-2482`).
pub(super) fn reload_config<C: CoreSurfaceHandle>(
    app: &Application,
    target: Target<'_, C>,
    opts: rustty_apprt_api::action::ReloadConfig,
) -> Result<(), ReloadConfigError> {
    // Tell systemd that reloading has started, but only once startup is
    // complete. A reload during startup is not a reload to systemd.
    //
    // (`:2445-2448`, and — via the trailing `notify::ready()` after the
    // body — `:2451`. `notify_systemd`/the `systemd_ready` gate added by
    // `4eb308831`, P7-W8 T3: syncing the color scheme during startup can
    // trigger a config reload before `startup_signals` has installed the
    // SIGUSR2 handler, and systemd 262+ refuses to start a
    // `Type=notify-reload` unit whose reload signal has no handler if it
    // sees `RELOADING=1`/`READY=1` that early.) The reference's
    // `defer if (notify_systemd) systemd.notify.ready()` (`:2451`) must
    // run on EVERY exit path (including the `?` early-returns of the
    // hard-reload load), so the body runs in an inner closure and
    // `ready()` fires unconditionally (subject to the same gate)
    // afterwards.
    let notify_systemd = app.imp().systemd_ready.get();
    if notify_systemd {
        rustty_os::systemd::notify::reloading();
    }
    let result = reload_config_inner(app, target, opts);
    // When we exit this function tell systemd that reloading has finished.
    if notify_systemd {
        rustty_os::systemd::notify::ready();
    }
    result
}

/// The body of [`reload_config`], factored out so the caller's
/// `systemd.notify.ready()` runs on every exit path (the reference's
/// `defer`, `application.zig:2451`).
fn reload_config_inner<C: CoreSurfaceHandle>(
    app: &Application,
    target: Target<'_, C>,
    opts: rustty_apprt_api::action::ReloadConfig,
) -> Result<(), ReloadConfigError> {
    // Get our config object.
    //
    // (`:2453-2472`.)
    let config: Config = if opts.soft {
        // Soft-reloading applies conditional logic to the existing loaded
        // config so we return that as-is (but take a reference).
        //
        // (`:2458-2461`, `self.private().config.ref()`.)
        match app.get_config() {
            Some(c) => c,
            // No config set yet (pre-construction) — nothing to reload.
            None => return Ok(()),
        }
    } else {
        // Hard reload, load a new config completely.
        //
        // (`:2464-2470`.) The reference
        // wraps the loaded `CoreConfig` in a `Config` GObject (which clones it),
        // so the local load result may drop here.
        //
        // `var config = try CoreConfig.load(alloc);` (`:2466`): propagated,
        // not logged (N311).
        let core_config = CoreConfig::load().map_err(ReloadConfigError::Load)?;
        Config::new(&core_config)
    };

    // Update the proper target. This will trigger a `config_change`
    // apprt action which will propagate the config properly to our
    // property system.
    //
    // (`:2477-2481`.)
    match target {
        // `.app => try self.core().updateConfig(self.rt(), config.get())`
        // (`:2472-2475`).
        Target::App => app
            .imp()
            .update_config_app(config.get())
            .map_err(ReloadConfigError::Core)?,
        // `.surface => |core| try core.updateConfig(config.get())` (`:2477`).
        Target::Surface(v) => {
            let rt = v.rt_surface_ptr().cast::<ApprtSurface>();
            if !rt.is_null() {
                // SAFETY: same liveness contract as `widget`: for a `.surface`
                // action the core app hands the LIVE core surface whose
                // `rt_surface` points at the pinned apprt `Surface`, read on the
                // app thread. `core()` reads the embedded `*CoreSurface` backref.
                let core = unsafe { (*rt).core() };
                unsafe { &mut *core }
                    .updateConfig(config.get())
                    .map_err(|err| ReloadConfigError::Core(err.into()))?;
            }
        }
    }
    Ok(())
}

