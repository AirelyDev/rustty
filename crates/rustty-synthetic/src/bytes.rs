//! Generates bytes.
//!
//! PORT NOTE: `synthetic/Bytes.zig`.

use crate::generator::Generator;
use crate::io::{WriteFailed, Writer};
use crate::rand::Rng;

/// PORT NOTE: `std.ascii.control_code.esc`.
pub(crate) const ESC: u8 = 0x1b;
/// PORT NOTE: `std.ascii.control_code.bel`.
pub(crate) const BEL: u8 = 0x07;

/// PORT NOTE: `std.ascii.isPrint` — printable ASCII `0x20..=0x7E` (excludes DEL 0x7F
/// and everything >= 0x80).
pub(crate) const fn is_print(c: u8) -> bool {
    c >= 0x20 && c <= 0x7e
}

/// PORT NOTE: `std.ascii.isAlphabetic` — `A-Za-z`.
pub(crate) const fn is_alphabetic(c: u8) -> bool {
    (c >= b'A' && c <= b'Z') || (c >= b'a' && c <= b'z')
}

/// PORT NOTE: `std.ascii.isAlphanumeric` — `A-Za-z0-9`.
pub(crate) const fn is_alphanumeric(c: u8) -> bool {
    is_alphabetic(c) || (c >= b'0' && c <= b'9')
}

/// Generate an alphabet given a function that returns true/false for a
/// given byte.
///
/// PORT NOTE: `Bytes.generateAlphabet(comptime func)` — builds a `[]const u8` by
/// scanning `0..256` in ascending order, keeping the bytes for which `func`
/// returns true. The exact set and order of bytes must match. Modelled as an
/// accessor returning a `&'static [u8]` sliced from a const-evaluated fixed
/// 256-buffer + length.
macro_rules! generate_alphabet {
    ($vis:vis $fn_name:ident, |$c:ident| $pred:expr) => {
        $vis fn $fn_name() -> &'static [u8] {
            static BUF: ([u8; 256], usize) = {
                let mut buf = [0u8; 256];
                let mut i: usize = 0;
                let mut n: usize = 0;
                while i < 256 {
                    let $c: u8 = i as u8;
                    if $pred {
                        buf[n] = i as u8;
                        n += 1;
                    }
                    i += 1;
                }
                (buf, n)
            };
            &BUF.0[..BUF.1]
        }
    };
}
pub(crate) use generate_alphabet;

/// PORT NOTE: `Bytes` — the `@This()` struct.
pub struct Bytes<'a> {
    /// Random number generator.
    pub rand: Rng<'a>,

    /// The minimum and maximum length of the generated bytes.
    pub min_len: usize,
    pub max_len: usize,

    /// The possible bytes that can be generated. If a byte is duplicated
    /// in the alphabet, it will be more likely to be generated. That's a
    /// side effect of the generator, not an intended use case.
    pub alphabet: Option<&'static [u8]>,
}

impl<'a> Bytes<'a> {
    /// PORT NOTE: the struct-literal defaults (`min_len = 1`, `max_len =
    /// std.math.maxInt(usize)`, `alphabet = null`).
    pub fn new(rand: Rng<'a>) -> Bytes<'a> {
        Bytes {
            rand,
            min_len: 1,
            max_len: usize::MAX,
            alphabet: None,
        }
    }

    pub fn generator<'g, W: Writer<Error = WriteFailed>>(&'g mut self) -> Generator<'g, W> {
        fn next_trampoline<W: Writer<Error = WriteFailed>>(
            ptr: *mut (),
            writer: &mut W,
            max_len: usize,
        ) -> Result<(), WriteFailed> {
            let self_: &Bytes = unsafe { &*(ptr as *const Bytes) };
            self_.next(writer, max_len)
        }
        Generator::init(self as *mut Bytes as *mut (), next_trampoline::<W>)
    }

    /// Return a copy of the Bytes, but with a new alphabet.
    pub fn new_alphabet(&self, new_alphabet: Option<&'static [u8]>) -> Bytes<'a> {
        Bytes {
            rand: self.rand,
            alphabet: new_alphabet,
            min_len: self.min_len,
            max_len: self.max_len,
        }
    }

    /// Return a copy of the Bytes, but with a new min_len. The new min
    /// len cannot be more than the previous max_len.
    pub fn at_least(&self, new_min_len: usize) -> Bytes<'a> {
        Bytes {
            rand: self.rand,
            alphabet: self.alphabet,
            min_len: self.max_len.min(new_min_len),
            max_len: self.max_len,
        }
    }

    /// Return a copy of the Bytes, but with a new max_len. The new max_len cannot
    /// be more the previous max_len.
    pub fn at_most(&self, new_max_len: usize) -> Bytes<'a> {
        Bytes {
            rand: self.rand,
            alphabet: self.alphabet,
            min_len: self.min_len.min(self.max_len.min(new_max_len)),
            max_len: self.max_len.min(new_max_len),
        }
    }

    pub fn next<W: Writer<Error = WriteFailed>>(
        &self,
        writer: &mut W,
        max_len: usize,
    ) -> Result<(), WriteFailed> {
        let _ = self.at_most(max_len).write(writer)?;
        Ok(())
    }

    /// PORT NOTE: `Bytes.format` — NOT `Display`; a stateful side-effecting write of
    /// random bytes. Everywhere Zig invokes the `{f}` hook we call this.
    pub fn format<W: Writer<Error = WriteFailed>>(
        &self,
        writer: &mut W,
    ) -> Result<(), WriteFailed> {
        let _ = self.write(writer)?;
        Ok(())
    }

    /// Write some random data and return the number of bytes written.
    pub fn write<W: Writer<Error = WriteFailed>>(
        &self,
        writer: &mut W,
    ) -> Result<usize, WriteFailed> {
        assert!(self.min_len >= 1);
        assert!(self.max_len >= self.min_len);

        let len = self
            .rand
            .int_range_at_most_biased::<usize>(self.min_len, self.max_len);

        let mut buf = [0u8; 8];

        let mut remaining = len;
        while remaining > 0 {
            let data = &mut buf[0..remaining.min(8)];
            self.rand.bytes(data);
            if let Some(alphabet) = self.alphabet {
                for byte in data.iter_mut() {
                    *byte = alphabet[(*byte as usize) % alphabet.len()];
                }
            }
            writer.writeAll(data)?;
            remaining -= data.len();
        }

        Ok(len)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::io::FixedWriter;
    use crate::rand::DefaultPrng;

    #[test]
    fn bytes() {
        let prng = DefaultPrng::init(0);
        let mut buf = [0u8; 256];
        let mut writer = FixedWriter::fixed(&mut buf);
        let mut v = Bytes {
            rand: prng.random(),
            min_len: 256,
            max_len: 256,
            alphabet: None,
        };
        let gen = v.generator();
        gen.next(&mut writer, 256).unwrap();
        assert_eq!(256, writer.buffered().len());
    }
}
