/** Verifies the porting widget registry, generated data and fact references are consistent. */
import { readFileSync, existsSync } from "node:fs";
import { WIDGETS } from "../src/components/porting/lib/registry.ts";
import { sourceSegments } from "../src/components/porting/lib/source-links.ts";
import { linkFailures } from "./lib/porting-links-guard.mjs";

/** Collected failures; the script exits non-zero if any are recorded. */
const failures = [];

/** Records a failure message when condition is false. */
function check(condition, message) {
  if (!condition) failures.push(message);
}

/** ID_RE flags internal identifiers that must not appear in visible text. */
const ID_RE =
  /\b(UD\d+|N\d{1,3}|R\d{1,2}[a-z]?|G\d+[a-z]?|G-[A-Z]+|P\d+-W\d+|T\d+[a-z]|A\d)\b/;

/** TEXT_FIELDS are the registry fields rendered as text (the summary as the deck's screen-reader alternative). */
const TEXT_FIELDS = ["title", "label", "source", "caption", "deck", "summary"];

/** DATA_DIR holds the generated widget JSON and facts.json. */
const DATA_DIR = "src/app/porting/data";

/** MDX_PATH is the article source checked for fact and widget references. */
const MDX_PATH = "src/app/porting/content.mdx";

/** Returns the visible prose of an MDX document: fenced code blocks and JSX/HTML tags removed. */
function proseOf(mdx) {
  return mdx.replace(/^```[\s\S]*?^```[^\n]*$/gm, "").replace(/<[^>]+>/g, "");
}

/** facts maps fact id → fact record (generated by scripts/porting/build_data.py). */
const facts = JSON.parse(readFileSync(`${DATA_DIR}/facts.json`, "utf8"));

/** slugs is the set of registered widget slugs, filled while checking entries. */
const slugs = new Set();

for (const w of WIDGETS) {
  check(!slugs.has(w.slug), `duplicate slug ${w.slug}`);
  slugs.add(w.slug);
  for (const field of TEXT_FIELDS) {
    check(typeof w[field] === "string" && w[field].length > 0, `${w.slug}.${field} is empty`);
    if (typeof w[field] !== "string") continue;
    check(!ID_RE.test(w[field]), `${w.slug}.${field} contains an internal id: ${w[field].match(ID_RE)?.[0]}`);
    check(!/\bBun\b/.test(w[field]), `${w.slug}.${field} mentions Bun`);
  }
  check(w.minHeight.desktop >= 200 && w.minHeight.phone >= 200, `${w.slug} minHeight too small`);
  check(w.frame === "card" || w.frame === "terminal", `${w.slug} has an unknown frame ${w.frame}`);
  if (w.dataFile) {
    const path = `${DATA_DIR}/${w.dataFile}`;
    check(existsSync(path), `${w.slug}: missing ${path}`);
    if (existsSync(path)) {
      const data = JSON.parse(readFileSync(path, "utf8"));
      for (const k of [...w.requiredKeys, "_meta"]) check(k in data, `${w.slug}: data missing key ${k}`);
      check(readFileSync(path).length < 200 * 1024, `${w.slug}: data over 200 KB`);
    }
  }
}

/** mdx is the article source, or "" before the article exists. */
const mdx = existsSync(MDX_PATH) ? readFileSync(MDX_PATH, "utf8") : "";
for (const [, id] of mdx.matchAll(/<Fact id="([a-z0-9_]+)"/g)) check(id in facts, `unknown fact id ${id}`);
for (const [, slug] of mdx.matchAll(/<PortingWidget slug="([a-z0-9-]+)"/g)) {
  check(slugs.has(slug), `unknown widget ${slug}`);
}
check(!ID_RE.test(proseOf(mdx)), `content.mdx prose contains an internal id: ${proseOf(mdx).match(ID_RE)?.[0]}`);

/**
 * NUMBER_RE finds a number as written in text: digits with internal thousands
 * separators, decimals or clock colons ("1,142", "88.6", "20:00"), not digits
 * inside a word or commit hash.
 */
const NUMBER_RE = /(?<![\w.,:])\d+(?:[.,:]\d+)*(?![\w])/g;

/** Returns the numbers written in text, thousands separators removed. */
function numbersIn(text) {
  return new Set([...text.matchAll(NUMBER_RE)].map(([n]) => n.replace(/,(?=\d{3}\b)/g, "")));
}

/**
 * Returns the rendered prose of the `## ` section holding a widget: from its
 * heading to the next one, each <Fact> replaced by its display text, then
 * code blocks and tags removed. Empty when the widget is not placed.
 */
function sectionProseOf(slug) {
  const at = mdx.indexOf(`<PortingWidget slug="${slug}"`);
  if (at < 0) return "";
  const start = mdx.lastIndexOf("\n## ", at);
  const next = mdx.indexOf("\n## ", at);
  const section = mdx.slice(start < 0 ? 0 : start, next < 0 ? mdx.length : next);
  return proseOf(section.replace(/<Fact id="([a-z0-9_]+)"\s*\/>/g, (_, id) => facts[id]?.display ?? ""));
}

// A deck says what the widget adds beyond its section's prose: it never repeats a number the prose states.
for (const w of WIDGETS) {
  if (typeof w.deck !== "string") continue;
  const prose = numbersIn(sectionProseOf(w.slug));
  for (const n of numbersIn(w.deck)) check(!prose.has(n), `${w.slug}.deck repeats ${n}, which its section's prose states`);
}

/**
 * REFERENCE_PIN_RE finds "pin" meaning the Ghostty reference commit, the port's internal word
 * (mirrors referencePinRe in verify-porting-helpers.mjs and REFERENCE_PIN_RE in
 * test_build_data.py). The verb and adjective ("pins a version", "one pinned commit") and
 * Ghostty's Pin type do not match.
 */
const REFERENCE_PIN_RE = /\b(?:the|at|current|new|each|Ghostty's)(?: (?:first|last|next|previous|current|new|old))? pin\b|\bpin (?:moves?|moved|advances?)\b|\b[Cc]urrent[- ]pin\b|\bPin \+\d|\b[Uu]pstream pin\b/;
check(
  !REFERENCE_PIN_RE.test(proseOf(mdx)),
  `content.mdx prose says "pin" for the reference commit: ${proseOf(mdx).match(REFERENCE_PIN_RE)?.[0]}`,
);

/** BUN_SECTION_HEADING is the only section whose prose may mention Bun (the one credit to Bun's post). */
const BUN_SECTION_HEADING = /^## The method matures[ \t]*$/m;

/** Returns prose with the Bun-credit section (its heading up to the next `## ` heading) removed. */
function proseOutsideBunSection(prose) {
  const start = prose.search(BUN_SECTION_HEADING);
  if (start < 0) return prose;
  const headingEnd = prose.indexOf("\n", start);
  const bodyStart = headingEnd < 0 ? prose.length : headingEnd + 1;
  const next = prose.slice(bodyStart).search(/^## /m);
  const end = next < 0 ? prose.length : bodyStart + next;
  return prose.slice(0, start) + prose.slice(end);
}

/** bunOutside is any mention of Bun in prose outside the Bun-credit section. */
const bunOutside = proseOutsideBunSection(proseOf(mdx)).match(/^.*\bBun\b.*$/im);
check(!bunOutside, `content.mdx mentions Bun outside "## The method matures": ${bunOutside?.[0]}`);

/**
 * HEDGE_BEFORE_FACT_RE finds a hedge word right before a <Fact>, capturing the
 * hedge and the fact id; a fact whose display already hedges ("about 56×",
 * "~$23.8k") must not get a second one ("about about 56×").
 */
const HEDGE_BEFORE_FACT_RE =
  /\b(about|around|roughly|nearly|approximately)\s+<Fact id="([a-z0-9_]+)"|(~)\s*<Fact id="([a-z0-9_]+)"/gi;

/** Returns true when a fact's display text already starts with a hedge. */
function displayHedges(id) {
  return /^(about\b|~)/i.test(facts[id]?.display ?? "");
}

for (const m of mdx.matchAll(HEDGE_BEFORE_FACT_RE)) {
  const hedge = m[1] ?? m[3];
  const id = m[2] ?? m[4];
  check(
    !displayHedges(id),
    `content.mdx doubles a hedge: "${hedge}" before <Fact id="${id}" />, whose display is "${facts[id]?.display}"`,
  );
}

/** commits maps each linkable commit token to "<repo>:<sha>" (generated from the research link map). */
const commits = JSON.parse(readFileSync(`${DATA_DIR}/commits.json`, "utf8"));
for (const f of linkFailures({ mdx, facts, commits })) failures.push(`content.mdx links: ${f}`);
for (const w of WIDGETS) {
  check(/^https:\/\/github\.com\//.test(w.sourceHref ?? ""), `${w.slug}: source pill has no GitHub link (sourceHref)`);
  // Each part of the source line links on its own: every key must name text in
  // `source`, on word boundaries and without overlap (sourceSegments throws
  // otherwise), and every target must be an absolute https URL.
  try {
    sourceSegments(w.source, w.sourceLinks ?? {});
  } catch (e) {
    failures.push(`${w.slug}: ${e.message}`);
  }
  for (const [key, href] of Object.entries(w.sourceLinks ?? {})) {
    check(/^https:\/\/[^\s]+$/.test(href), `${w.slug}: source link "${key}" is not an absolute https URL`);
  }
  check(w.sourceHrefLabel === undefined || w.sourceHrefLabel.length > 0, `${w.slug}: sourceHrefLabel is empty`);
}

if (failures.length) {
  console.error(failures.join("\n"));
  process.exit(1);
}
console.log(`porting registry OK (${WIDGETS.length} widgets, ${Object.keys(facts).length} facts)`);
