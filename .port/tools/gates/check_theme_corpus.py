#!/usr/bin/env python3
"""
check_theme_corpus.py — GATE G-THEMES: the vendored iterm2 theme corpus is
byte-exact against a committed per-file digest manifest [R1].

Why this exists (`P3-W9 T5` step 2). `xtask/src/res_themes.rs` asserts the
emitted corpus has EXACTLY N files. That catches an added or deleted theme and
nothing else: **content drift inside an existing theme file is invisible to a
count.** The corpus is 602 files of upstream data that no rustty test reads the
body of (`res_themes.rs` spot-checks exactly one file for the substring
`palette = 0=`), it is shipped to users by `xtask resources`, and it is
re-vendored by hand from a tarball. A single mistyped hex value, a stray editor
newline, or a partial re-vendor would ship silently.

This gate stores a SHA-256 per file plus a total digest over the sorted
`name<TAB>digest` lines, and fails on:
  * any content change in an existing theme,
  * any added or removed theme,
  * any manifest edit that does not match the files (the total digest is
    recomputed from the per-file rows, so hand-editing one row is caught).

Regenerate deliberately, and only when re-vendoring:
    python3 .port/tools/gates/check_theme_corpus.py --write

`.md` files in the corpus directory are rustty's own provenance/licence notes,
are excluded from the shipped set by `res_themes.rs`, and are excluded here.

Exit 0 = GREEN ; 1 = RED (corpus drift) ; 2 = usage/blocked.
"""
import hashlib
import os
import sys

GATES = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(GATES, "..", "..", ".."))
CORPUS = os.path.join(ROOT, "crates", "rustty-extra", "themes")
MANIFEST = os.path.join(ROOT, "crates", "rustty-extra", "themes.manifest")


def rows():
    """(name, sha256) for every non-`.md` corpus file, sorted by name."""
    out = []
    for name in sorted(os.listdir(CORPUS)):
        if name.endswith(".md"):
            continue
        p = os.path.join(CORPUS, name)
        if not os.path.isfile(p):
            continue
        with open(p, "rb") as fh:
            out.append((name, hashlib.sha256(fh.read()).hexdigest()))
    return out


def render(rs):
    body = "".join(f"{n}\t{d}\n" for n, d in rs)
    total = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return (
        "# rustty vendored iterm2 theme corpus — per-file SHA-256 manifest.\n"
        "# GENERATED by .port/tools/gates/check_theme_corpus.py --write.\n"
        "# Do not hand-edit: the total digest is computed over the rows below.\n"
        f"# files {len(rs)}\n"
        f"# total {total}\n" + body
    )


def parse(text):
    rs, total, count = [], None, None
    for line in text.split("\n"):
        if not line:
            continue
        if line.startswith("#"):
            if line.startswith("# total "):
                total = line[len("# total ") :].strip()
            elif line.startswith("# files "):
                count = int(line[len("# files ") :].strip())
            continue
        name, _, digest = line.partition("\t")
        rs.append((name, digest))
    return rs, total, count


def main():
    if not os.path.isdir(CORPUS):
        print(f"BLOCKED: no corpus at {CORPUS}")
        return 2

    actual = rows()

    if "--write" in sys.argv:
        with open(MANIFEST, "w", encoding="utf-8") as fh:
            fh.write(render(actual))
        print(f"WROTE {MANIFEST}: {len(actual)} files")
        return 0

    if not os.path.exists(MANIFEST):
        print(f"BLOCKED: no manifest at {MANIFEST} (run with --write)")
        return 2

    expected, total, count = parse(open(MANIFEST, encoding="utf-8").read())

    # Self-consistency: the manifest's own header must match its rows, so a
    # hand-edited row cannot be laundered by also editing the header count.
    body = "".join(f"{n}\t{d}\n" for n, d in expected)
    recomputed = hashlib.sha256(body.encode("utf-8")).hexdigest()
    if recomputed != total or count != len(expected):
        print("RED: the manifest is internally inconsistent (hand-edited?)")
        print(f"  header total {total}  recomputed {recomputed}")
        print(f"  header files {count}  rows {len(expected)}")
        return 1

    exp = dict(expected)
    act = dict(actual)
    added = sorted(set(act) - set(exp))
    removed = sorted(set(exp) - set(act))
    changed = sorted(n for n in set(exp) & set(act) if exp[n] != act[n])

    if not (added or removed or changed):
        print(f"G-THEMES: vendored theme corpus byte-exact ({len(actual)} files)")
        return 0

    print("RED: the vendored theme corpus does not match its digest manifest")
    for n in added:
        print(f"  ADDED    {n}")
    for n in removed:
        print(f"  REMOVED  {n}")
    for n in changed:
        print(f"  CHANGED  {n}  manifest={exp[n][:16]}…  actual={act[n][:16]}…")
    print("If this is a deliberate re-vendor, rerun with --write and commit.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
